export interface CraftingConceptItem {
  id: string
  name: string
  image: string
}

export interface CraftingConceptGroup {
  id: string
  name: string
  items: CraftingConceptItem[]
}

function createGroup(id: string, name: string, items: Array<[string, string]>): CraftingConceptGroup {
  return {
    id,
    name,
    items: items.map(([itemId, itemName]) => ({
      id: itemId,
      name: itemName,
      image: `/assets/crafting/${itemId}.png`,
    })),
  }
}

