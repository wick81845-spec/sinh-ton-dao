const fishingLootItemDefinitions = Object.fromEntries(fishingLootCatalog
  .filter((loot) => loot.itemId !== 'item_wood')
  .map((loot) => [
    loot.itemId,
    {
      name: loot.name,
      description: loot.description,
      category: 'resource',
      maxStack: 20,
      weight: loot.kind === 'treasure' ? 1 : 0.3,
      icon: loot.kind === 'treasure' ? '◇' : '♻',
      image: loot.image,
      tone: 'stone',
      usable: false,
      tradable: loot.kind === 'treasure',
    },
  ])) as Record<FishingLootItemId, ItemDefinition>

export const itemDefinitions: Record<ItemId, ItemDefinition> = {
  ...staticItemDefinitions,
  ...fishItemDefinitions,
  ...fishingRodItemDefinitions,
  ...fishingLootItemDefinitions,
}

export function isAccessoryItem(itemId: ItemId): boolean {
  const item = itemDefinitions[itemId]
  return item.usable && (
    item.hungerRestore !== undefined
    || item.thirstRestore !== undefined
    || item.healthRestore !== undefined
    || (item.curesAilments?.length ?? 0) > 0
  )
}
